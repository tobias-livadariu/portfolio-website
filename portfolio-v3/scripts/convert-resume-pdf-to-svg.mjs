#!/usr/bin/env node

import { spawn } from "node:child_process";
import {
  access,
  mkdir,
  mkdtemp,
  readFile,
  rename,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";

const inputPath = resolve(process.argv[2] ?? "public/resume.pdf");
const outputPath = resolve(process.argv[3] ?? "public/resume.svg");

function run(command, args) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, { stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";

    child.stdout.on("data", (chunk) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
    });
    child.on("error", (error) => {
      reject(
        new Error(
          `Could not run ${command}. Install Poppler first (for example, \`brew install poppler\`).\n${error.message}`,
        ),
      );
    });
    child.on("close", (code) => {
      if (code === 0) {
        resolvePromise({ stderr, stdout });
      } else {
        reject(
          new Error(
            `${command} exited with code ${code}.\n${stderr || stdout}`,
          ),
        );
      }
    });
  });
}

function prefixPageIds(svgBody, pageIndex) {
  const prefix = `resume-page-${pageIndex}-`;
  const ids = Array.from(
    svgBody.matchAll(/\bid="([^"]+)"/g),
    (match) => match[1],
  );

  return ids.reduce((body, id) => {
    const escapedId = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

    return body
      .replaceAll(`id="${id}"`, `id="${prefix}${id}"`)
      .replace(
        new RegExp(`url\\(#${escapedId}\\)`, "g"),
        `url(#${prefix}${id})`,
      )
      .replace(
        new RegExp(`(["'])#${escapedId}(["'])`, "g"),
        `$1#${prefix}${id}$2`,
      );
  }, svgBody);
}

function readSvgPage(svg, pageIndex) {
  const rootMatch = svg.match(
    /<svg\b[^>]*\bviewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>\s*$/,
  );

  if (!rootMatch) {
    throw new Error(
      `Poppler produced an SVG page with an unexpected structure (page ${pageIndex}).`,
    );
  }

  const viewBox = rootMatch[1].trim().split(/\s+/).map(Number);
  if (
    viewBox.length !== 4 ||
    viewBox.some((value) => !Number.isFinite(value))
  ) {
    throw new Error(
      `Poppler produced an invalid SVG viewBox on page ${pageIndex}.`,
    );
  }

  const [, , width, height] = viewBox;
  return {
    body: prefixPageIds(rootMatch[2], pageIndex),
    height,
    viewBox: viewBox.join(" "),
    width,
  };
}

async function main() {
  await access(inputPath);
  const { stdout: pdfInfo } = await run("pdfinfo", [inputPath]);
  const pageCount = Number(pdfInfo.match(/^Pages:\s+(\d+)/m)?.[1]);

  if (!Number.isInteger(pageCount) || pageCount < 1) {
    throw new Error("Could not determine the PDF page count with pdfinfo.");
  }

  const temporaryDirectory = await mkdtemp(`${tmpdir()}/portfolio-resume-svg-`);

  try {
    const pages = [];

    for (let pageNumber = 1; pageNumber <= pageCount; pageNumber += 1) {
      const pagePath = resolve(temporaryDirectory, `page-${pageNumber}.svg`);
      await run("pdftocairo", [
        "-svg",
        "-f",
        String(pageNumber),
        "-l",
        String(pageNumber),
        inputPath,
        pagePath,
      ]);
      pages.push(readSvgPage(await readFile(pagePath, "utf8"), pageNumber));
    }

    const width = Math.max(...pages.map((page) => page.width));
    const height = pages.reduce((sum, page) => sum + page.height, 0);
    let offsetY = 0;
    const pageElements = pages.map((page) => {
      const element = `<svg x="0" y="${offsetY}" width="${page.width}" height="${page.height}" viewBox="${page.viewBox}">${page.body}</svg>`;
      offsetY += page.height;
      return element;
    });
    const combinedSvg = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      "<!-- Generated by npm run resume:svg. Do not edit by hand. -->",
      `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${width}pt" height="${height}pt" viewBox="0 0 ${width} ${height}">`,
      ...pageElements,
      "</svg>",
      "",
    ].join("\n");
    const temporaryOutputPath = `${outputPath}.tmp-${process.pid}`;

    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(temporaryOutputPath, combinedSvg);
    await rename(temporaryOutputPath, outputPath);
    console.log(
      `Created ${outputPath} from ${pageCount} page${pageCount === 1 ? "" : "s"} of ${inputPath}.`,
    );
  } finally {
    await rm(temporaryDirectory, { force: true, recursive: true });
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
