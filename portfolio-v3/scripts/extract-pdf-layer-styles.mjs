#!/usr/bin/env node

import postcss from "postcss";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve } from "node:path";

/* pdf.js ships one stylesheet for its whole viewer application: dialogs,
   sidebars, the annotation editor, form layers and more, about 230 KB. The
   résumé viewer builds only two of those pieces on top of each page's canvas,
   the selectable text layer and the link layer, so it needs only their rules.

   This script copies those rules, unchanged and in their original order,
   into src/modals/resume/pdf-layers.css, which the résumé viewer imports in
   place of the full stylesheet. Run it again after changing the pdfjs-dist
   version:

     npm run pdf-layer-styles

   Pass --dropped to also print the selectors of every rule left out, which is
   how the copy is checked: none of them may match an element on the page. */
const LAYER_SELECTOR =
  /\.(?:textLayer|textLayerImages|annotationLayer)(?![\w-])/;
const OUTPUT_PATH = resolve("src/modals/resume/pdf-layers.css");

const require = createRequire(import.meta.url);
const sourcePath = require.resolve("pdfjs-dist/web/pdf_viewer.css");
const { version } = require("pdfjs-dist/package.json");
const root = postcss.parse(await readFile(sourcePath, "utf8"), {
  from: sourcePath,
});
const droppedSelectors = [];

const isLayerRule = (node) =>
  node.type === "rule" && LAYER_SELECTOR.test(node.selector);
const isRootRule = (node) =>
  node.type === "rule" && node.selector.trim() === ":root";

/* First pass: keep the layer rules, and set the `:root` rules aside. Those
   mostly define custom properties, which are kept only where a kept rule
   reads them. Their few ordinary declarations (`color-scheme`) apply to the
   whole page today, so they are kept to leave the page exactly as it was. */
const pruneContainer = (container) => {
  container.each((node) => {
    if (node.type === "comment") {
      // Only the licence notice at the top of the file is kept.
      if (container !== root || !node.text.includes("Licensed under")) {
        node.remove();
      }
    } else if (node.type === "atrule" && node.nodes) {
      pruneContainer(node);

      if (node.nodes.length === 0) {
        node.remove();
      }
    } else if (isRootRule(node)) {
      node.isRootRule = true;
    } else if (!isLayerRule(node)) {
      if (node.type === "rule") {
        droppedSelectors.push(node.selector.replace(/\s+/g, " "));
      }
      node.remove();
    }
  });
};

pruneContainer(root);

let keptStyles = "";
root.walkRules((rule) => {
  if (!rule.isRootRule) {
    keptStyles += rule.toString();
  }
});

/* Removes what is left empty, working outward: a media block inside a
   `:root` rule, the rule itself, then a media block around it. */
const removeIfEmpty = (node) => {
  if (node.type === "root" || node.nodes.length > 0) {
    return;
  }

  const parent = node.parent;

  node.remove();
  removeIfEmpty(parent);
};

root.walkRules((rule) => {
  if (!rule.isRootRule) {
    return;
  }

  rule.walkDecls((declaration) => {
    if (
      declaration.prop.startsWith("--") &&
      !keptStyles.includes(`var(${declaration.prop}`)
    ) {
      const parent = declaration.parent;

      declaration.remove();
      removeIfEmpty(parent);
    }
  });
});

const header = [
  `/* Generated by \`npm run pdf-layer-styles\` from pdfjs-dist ${version}`,
  "   (web/pdf_viewer.css). Do not edit by hand.",
  "",
  "   Only the rules for the text layer and the link layer, copied unchanged",
  "   and in their original order. See scripts/extract-pdf-layer-styles.mjs. */",
  "",
].join("\n");

await writeFile(OUTPUT_PATH, `${header}\n${root.toString().trim()}\n`);
console.log(
  `Wrote ${OUTPUT_PATH}; left out ${droppedSelectors.length} unrelated rules.`,
);

if (process.argv.includes("--dropped")) {
  console.log(JSON.stringify(droppedSelectors));
}
