#!/usr/bin/env node

import { chromium } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const baseUrl = process.argv[2] ?? "http://127.0.0.1:5173/portfolio/";
const outputDirectory = resolve(process.argv[3] ?? "public/posters");

function pngDimensions(buffer) {
  const pngSignature = "89504e470d0a1a0a";
  if (buffer.subarray(0, 8).toString("hex") !== pngSignature) {
    throw new Error("Playwright returned an unexpected screenshot format.");
  }

  return {
    height: buffer.readUInt32BE(20),
    width: buffer.readUInt32BE(16),
  };
}

function screenshotSvg(png) {
  const { height, width } = pngDimensions(png);
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    "<!-- Generated by npm run modal-posters. Do not edit by hand. -->",
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`,
    `  <image width="${width}" height="${height}" preserveAspectRatio="none" href="data:image/png;base64,${png.toString("base64")}"/>`,
    "</svg>",
    "",
  ].join("\n");
}

async function waitForStartupReveal(page) {
  await page
    .locator('.bg-transition-overlay[data-startup="true"]')
    .waitFor({ state: "detached", timeout: 20_000 });
}

async function openPortfolio(page) {
  await page.mouse.move(900, 120);
  await page.mouse.wheel(0, 160);
  await page.locator(".modal-layer-open").waitFor();

  return page.locator('.modal-panel[aria-label="PORTFOLIO section"]');
}

async function scrollIntoModalViewport(locator) {
  await locator.evaluate((element) => {
    const scrollRoot = element.closest(".modal-scroll-root");

    if (!(scrollRoot instanceof HTMLElement)) {
      throw new Error("Scene is not inside the modal scroll root.");
    }

    scrollRoot.scrollTop += element.getBoundingClientRect().top - 80;
    scrollRoot.dispatchEvent(new Event("scroll"));
  });
}

async function main() {
  const browser = await chromium.launch({ headless: true });

  try {
    const page = await browser.newPage({
      deviceScaleFactor: 1,
      viewport: { height: 900, width: 1280 },
    });
    const url = new URL(baseUrl);
    url.searchParams.set("captureModalScenePosters", "1");

    await page.goto(url.toString());
    await waitForStartupReveal(page);
    const activePanel = await openPortfolio(page);
    const scenes = [
      {
        name: "modal-incoming.svg",
        target: activePanel.locator(".modal-incoming"),
      },
      {
        name: "modal-shopify.svg",
        target: activePanel.locator(".modal-story-canvas-shell").nth(0),
      },
      {
        name: "modal-ideanotion.svg",
        target: activePanel.locator(".modal-story-canvas-shell").nth(1),
      },
    ];

    await mkdir(outputDirectory, { recursive: true });

    for (const scene of scenes) {
      await scrollIntoModalViewport(scene.target);
      await scene.target
        .locator('[data-scene-ready="true"]')
        .waitFor({ state: "attached", timeout: 20_000 });
      await page.evaluate(
        () =>
          new Promise((resolvePromise) =>
            requestAnimationFrame(() => requestAnimationFrame(resolvePromise)),
          ),
      );
      const clip = await scene.target.boundingBox();
      if (!clip) {
        throw new Error(`Could not measure ${scene.name}.`);
      }
      const screenshot = await page.screenshot({
        animations: "disabled",
        clip,
        type: "png",
      });
      await writeFile(
        resolve(outputDirectory, scene.name),
        screenshotSvg(screenshot),
      );
      console.log(`Created ${resolve(outputDirectory, scene.name)}.`);
    }
  } finally {
    await browser.close();
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
